export function getScheduleForPathway(id: AdmissionPathwayId) {
  const pathway = admissionPathways.find(pathway => pathway.id === id);
  if (!pathway) return scheduleMonths;
  return scheduleMonths.map(group => ({
    ...group,
    rows: group.rows.map(row => ({ ...row, items: row.items.filter(item => pathway.match.test(item)) }))
      .filter(row => row.items.length > 0),
  })).filter(group => group.rows.length > 0);
}

