export const departmentCategories = categorySeeds.map((category) => ({
  name: category.name,
  groups: category.groups.map((group) => ({
    name: group.name,
    departments: group.departments.map(([name, intro, practice, check]): Department => ({ name, category: category.name, group: group.name, intro, practice, check })),
  })),
}));

export const departments = departmentCategories.flatMap((category) => category.groups.flatMap((group) => group.departments));
const departmentsByName = new Map(departments.map((department) => [department.name, department]));

export const departmentPath = (name: string) => `/departments/${encodeURIComponent(name)}`;
export const getDepartment = (name: string) => departmentsByName.get(name);
export const getDepartmentFromPath = (segment: string) => {
  try { return getDepartment(decodeURIComponent(segment)); } catch { return undefined; }
};
